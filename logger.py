    entry_id = log_interaction(
        query="What is prior authorization in Cerner Revenue Cycle?",
        classified_vertical="REVENUE_CYCLE",
        retrieved_chunks=[fake_chunk],
        response="Prior authorization in Cerner... [Source: rcm-prior-auth-overview.txt]",
        latency_ms=1234,
        session_id="test-session-abc123",
        rewritten_query="What is prior authorization in Cerner Revenue Cycle?",
        query_classification="in_scope",
        confidence="high",
        latency_retrieve_ms=210,
        latency_generate_ms=980,
        cache_hit=False,
    )
    print(f"  Entry ID: {entry_id}")

    print("[Test] Updating feedback to 'up'...")
    ok = update_feedback(entry_id, "up")
    print(f"  Updated: {ok}")

    logs = get_recent_logs(1)
    if logs:
        print(json.dumps(logs[-1], indent=2))

    print(f"\nLog file: {LOG_FILE}")


